"""Write core/own_game_layouts_sage.h: how uniform buffers moved from the game's 1.1.1 program to its 2.0.0 Switch 2
program (docs/SWITCH2_SHADERS.md, section 5), for converting Kadan's Switch 1 programs to the Switch 2.

    python tools/make_sage_layouts_header.py <1.1.1 folder> <2.0.0 folder> [--check]

Each folder holds game_uniform_layouts.py's game-layouts.tsv (block, SPIR-V member, game offset) and
game-layout-hashes.tsv (shader variable, game layout hash, stock hash) for that build. The header lists, per struct
whose layout hash differs between the builds, the old and new hash and every member whose offset moved (old start,
old end, new start; a member 2.0.0 lacks has new start -1).
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'core' / 'own_game_layouts_sage.h'


def offsets(path):
    blocks = {}
    for line in Path(path).read_text(encoding='utf-8').splitlines():
        parts = line.split('\t')
        if len(parts) == 3 and parts[2].isdigit():
            blocks.setdefault(parts[0], {})[parts[1]] = int(parts[2])
    return blocks


def hashes(path):
    out = {}
    for line in Path(path).read_text(encoding='utf-8').splitlines():
        parts = line.split('\t')
        if len(parts) >= 2 and parts[1].isdigit():
            out[parts[0]] = int(parts[1])
    return out


def header(old_dir, new_dir):
    old_b, new_b = offsets(Path(old_dir) / 'game-layouts.tsv'), offsets(Path(new_dir) / 'game-layouts.tsv')
    old_h, new_h = hashes(Path(old_dir) / 'game-layout-hashes.tsv'), hashes(Path(new_dir) / 'game-layout-hashes.tsv')
    rows = []
    for var in sorted(set(old_h) & set(new_h)):
        if old_h[var] == new_h[var]:
            continue
        members = []
        old_members = sorted(old_b.get(var, {}).items(), key=lambda kv: kv[1])
        for k, (name, start) in enumerate(old_members):
            end = old_members[k + 1][1] if k + 1 < len(old_members) else start + 16
            end = max(end, start + 4)
            new = new_b.get(var, {}).get(name, -1)
            if new != start:
                members.append((start, end, new, name))
        rows.append((var, old_h[var], new_h[var], members))
    lines = ['// Generated by tools/make_sage_layouts_header.py: do not edit.',
             '// How the game\'s uniform buffers moved from its 1.1.1 program to its 2.0.0 Switch 2 program: per struct whose',
             '// layout hash differs, the old and new hash and each member whose byte offset moved (old start, old end, new',
             '// start; -1 when 2.0.0 lacks the member). Read from both programs by game_uniform_layouts.py.',
             '#pragma once', '#include <cstdint>', '#include <vector>', '',
             'namespace P4MapKit { namespace CustomMaterial { namespace OwnSage {', '',
             'struct MovedMember { std::uint32_t old_start, old_end; std::int32_t new_start; };',
             'struct MovedLayout { const char* name; std::uint32_t old_hash, new_hash; std::vector<MovedMember> members; };', '',
             'inline const std::vector<MovedLayout>& SageMovedLayouts() {',
             '    static const std::vector<MovedLayout> table = {']
    for var, oh, nh, members in rows:
        body = ', '.join('{%du, %du, %d}' % (s, e, n) for s, e, n, _ in members)
        lines.append('        {"%s", %du, %du, {%s}},' % (var, oh, nh, body))
    lines += ['    };', '    return table;', '}', '', '}}}  // namespace P4MapKit::CustomMaterial::OwnSage', '']
    return '\n'.join(lines)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    text = header(args[0], args[1])
    if '--check' in sys.argv:
        same = OUT.is_file() and OUT.read_text(encoding='utf-8').replace('\r\n', '\n') == text
        print('up to date' if same else 'stale')
        return 0 if same else 1
    OUT.write_text(text, encoding='utf-8', newline='\n')
    print('wrote', OUT, text.count('\n'), 'lines')
    return 0


if __name__ == '__main__':
    sys.exit(main())
